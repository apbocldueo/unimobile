class BaseEvaluator(ABC):
    """The absolute base classes of all evaluation nodes 
    including AST nodes and specific plugins

    Args:
        ABC (_type_): _description_
    """
    _pipeline_phase = "⚖️ Evaluation"

    def __init__(self, params: Dict[str, Any], device: Any) -> None:
        self.params = params
        self.device = device
        
        namespace = getattr(self.__class__, '__plugin_namespace__', 'evaluator.unknown')
        name = getattr(self.__class__, '__plugin_name__', self.__class__.__name__)
        self.logger = get_plugin_logger(phase=self._pipeline_phase, namespace=namespace, plugin_name=name)

    def pre_evaluate(self, context: Dict[str, Any]) -> None:
        """Pre-run Hook
        The Agent is executed before running and is used to save environment snapshots, obtain initial values, etc
        By default, there is no action. 
        Subclasses can be overridden as needed.

        Args:
            context (Dict[str, Any]): _description_
        """
        pass

    def get_param(self, key: str, context: Dict[str, Any], default: Any = None, expected_type: type = str) -> Any:
        
        if key not in self.params:
            if default is not None:
                return default
            raise KeyError(f"[{self.__class__.__name__}] missing required param: '{key}'")
            
        return ParamHandler.get_and_render(self.params, key, context, expected_type)

    @abstractmethod
    def evaluate(self, context: Dict[str, Any]) -> EvalResult:
        """Core execution flow

        Args:
            context (Dict[str, Any]): Runtime global context

        Returns:
            EvalResult: A dictionary in the format of 
            {
                "pass": bool, 
                "reason": str, 
                "cost": float
            } 
        """
        pass