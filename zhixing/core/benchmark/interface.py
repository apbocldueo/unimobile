# ====================== Param initializer generator ======================
class BaseParamInitializerGenerator(ABC):
    gen_type: ParamInitializerPluginType

    _pipeline_phase = "🎲 Task param initialization"

    def __init__(self) -> None:
        namespace = getattr(self.__class__, '__plugin_namespace__', 'benchmark.task_init')
        name = getattr(self.__class__, '__plugin_name__', self.__class__.__name__)
        
        self.logger = get_plugin_logger(
            phase=self._pipeline_phase,
            namespace=namespace,
            plugin_name=name
        )

    @abstractmethod
    def generate(self, params: Dict[str, Any]) -> Any:
        """Execute task param generator·

        Args:
            params (Dict[str, Any]): task_initializer.configX.params

        Returns:
            Any:
        """
        pass


# ====================== Base environment initializer operation ======================
class BaseEnvironmentInitializerOperation(ABC):

    op_type: EnvironmentInitializerPluginType

    _pipeline_phase = "🛠️ Environment Initialization"

    def __init__(self) -> None:

        # Builder custom logger
        namespace = getattr(self.__class__, '__plugin_namespace__', 'benchmark.env_init')
        name = getattr(self.__class__, '__plugin_name__', self.__class__.__name__)

        self.logger = get_plugin_logger(
            phase=self._pipeline_phase,
            namespace=namespace,
            plugin_name=name
        )

    @abstractmethod
    def execute(self
                , meta: Dict[str, Any]
                , params: Dict[str, Any]) -> bool:
        """Execute environment initialization operation

        Args:
            meta (Dict[str, Any]): environment_initializer[].meta
            params (Dict[str, Any]): environment_initializer[].params

        Returns:
            bool: Whether the execution was successful
        """
        pass

