import { create } from "zustand";
import { english } from "./messages";

export type UiLocale = "zh-CN" | "en";
const STORAGE_KEY = "zx-studio-language-v1";

/** Read only an allowlisted display preference; unavailable storage keeps Chinese.
 * @returns The persisted language, or the existing interface default.
 */
function readLocale(): UiLocale {
  try {
    const value = typeof window === "undefined" ? null : window.localStorage.getItem(STORAGE_KEY);
    return value === "en" ? "en" : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

/** Apply display metadata without touching workspace data or triggering requests.
 * @param locale The validated interface language.
 */
export function applyUiLocale(locale: UiLocale): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.title = locale === "en" ? "ZhiXing · Mobile Agent" : "知行 ZhiXing · Mobile Agent";
}

type LocaleState = { locale: UiLocale; setLocale: (locale: UiLocale) => void };

export const useUiLocaleStore = create<LocaleState>((set) => ({
  locale: readLocale(),
  /** Persist a display-only preference; blocked storage still allows live switching.
   * @param locale An allowlisted language identifier.
   */
  setLocale(locale) {
    if (locale !== "en" && locale !== "zh-CN") return;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Private or full storage must not prevent an in-memory language change.
    }
    applyUiLocale(locale);
    set({ locale });
  },
}));

/** Subscribe a presentation component without remounting its editor or form state.
 * @returns The current interface language.
 */
export function useUiLocale(): UiLocale {
  return useUiLocaleStore((state) => state.locale);
}

/** Translate trusted interface copy only; unknown values remain unchanged.
 * @param source A static Chinese UI message, never arbitrary user content.
 * @returns The localized display string.
 */
export function uiText(source: string): string {
  return useUiLocaleStore.getState().locale === "en" ? english[source] ?? source : source;
}

/** Format trusted copy with separately supplied, untranslated argument values.
 * @param parts Static template fragments generated by the caller's tagged literal.
 * @param values Runtime data interpolated exactly once after message selection.
 * @returns A localized plain string; React retains its ordinary text escaping.
 */
export function uiMessage(parts: TemplateStringsArray, ...values: unknown[]): string {
  const key = parts.reduce((result, part, index) => result + (index ? `{${index - 1}}` : "") + part, "");
  const pattern = uiText(key);
  return pattern.replace(/\{(\d+)\}/g, (placeholder, index: string) => {
    const position = Number(index);
    return position < values.length ? String(values[position]) : placeholder;
  });
}

