@pytest.mark.parametrize("checkpoint_format", ["full","lora"])
def test_native_model_is_lazy_and_preserves_original_call_conventions(tmp_path,monkeypatch,checkpoint_format):
    """Exercise loading/tokenization/chat boundaries without a model runtime.

    Args:
        tmp_path: Existing test screenshot path.
        monkeypatch: Replace only optional model libraries.
        checkpoint_format: Explicit full or LoRA loader selection.
    Raises:
        AssertionError: The source or execution contract is violated.
    Returns:
        None.
    """
    import zhixing.plugins.llm.seeclick_llm as module
    calls = []

    class Backend:
        """Return a fake response through the original Qwen chat API."""

        def eval(self):
            """Select inference mode and return the backend.

            Returns:
                Backend: This test double.
            """
            return self

        def chat(self,tokenizer,query,history):
            """Record query ordering and the explicitly empty chat history.

            Args:
                tokenizer: Original tokenizer double.
                query: Encoded current image and prompt.
                history: Required None per original source.
            Returns:
                tuple: Terminal prediction and unused model history.
            """
            calls.append(("chat",query,history))
            return '{"action_type":10}', ["must not be reused"]

    class Loader:
        """Record checkpoint settings and return a small backend."""

        @classmethod
        def from_pretrained(cls,path,**kwargs):
            """Record a source-compatible checkpoint construction.

            Args:
                path: Model path.
                kwargs: Runtime/cache/revision settings.
            Returns:
                Backend: No weights or model packages are used.
            """
            calls.append(("model",path,kwargs))
            return Backend()

    class Tokenizer:
        """Record image-first input while providing the normal tokenizer API."""

        @classmethod
        def from_pretrained(cls,path,**kwargs):
            """Record matching tokenizer settings.

            Args:
                path: Tokenizer reference.
                kwargs: Cache/revision settings.
            Returns:
                Tokenizer: New tokenizer double.
            """
            calls.append(("tokenizer",path,kwargs))
            return cls()

        def from_list_format(self,parts):
            """Pass through the exact image-first query for inspection.

            Args:
                parts: Original Qwen query list.
            Returns:
                list: Input query unchanged.
            """
            return parts

    class Generation:
        """Record generation configuration separately from checkpoint weights."""

        @classmethod
        def from_pretrained(cls,path,**kwargs):
            """Provide opaque generation settings without overriding defaults.

            Args:
                path: Matching Qwen generation configuration.
                kwargs: Cache/revision settings.
            Returns:
                object: Opaque settings object.
            """
            calls.append(("generation",path,kwargs))
            return object()

    modules = {"torch":SimpleNamespace(no_grad=nullcontext),
        "transformers":SimpleNamespace(AutoTokenizer=Tokenizer,AutoModelForCausalLM=Loader,GenerationConfig=Generation),
        "peft":SimpleNamespace(AutoPeftModelForCausalLM=Loader)}

    def load(name):
        """Track optional imports at the first actual model invocation.

        Args:
            name: Requested optional module.
        Returns:
            object: Matching test-only transport/model module.
        """
        calls.append(("import",name))
        return modules[name]

    monkeypatch.setattr(module,"import_module",load)
    model = SeeClickLLM("model","qwen",checkpoint_format,revision="model-revision",qwen_revision="qwen-revision")
    assert calls == []
    image = tmp_path / "screen.png"
    Image.new("RGB",(100,200)).save(image)
    for _ in range(2):
        assert model.generate("prompt",[str(image)]) == '{"action_type":10}'
    assert len([call for call in calls if call[0] == "model"]) == 1
    assert [call for call in calls if call[0] == "chat"] == [
        ("chat",[{"image":str(image)},{"text":"prompt"}],None)] * 2
    for call in calls:
        if call[0] in ("tokenizer","model","generation"):
            assert call[2]["local_files_only"] is True
    model_options = next(call[2] for call in calls if call[0] == "model")
    assert model_options["revision"] == "model-revision"
    assert ("bf16" in model_options) is (checkpoint_format == "full")
    assert (("import","peft") in calls) is (checkpoint_format == "lora")
    # Also resolve the default nested model dependency through the real Catalog
    # and execute the complete graph with only the optional libraries replaced.
    result = compile_agent(build_seeclick_graph(model_path="model",qwen_path="qwen",
        checkpoint_format=checkpoint_format)).run("Open settings",
        AgentRunConfig(artifact_root=tmp_path / "runs"),device=Android())
    assert result.status is RunStatus.SUCCESS, result
    assert result.interaction_count == 0
