class Model:
    """Script only the external model; leave prompt, parser and graph untouched."""

    def __init__(self, responses):
        """Store a finite response script and input log.

        Args:
            responses: Ordered response texts or an exception to raise.
        Returns:
            None.
        """
        self.responses, self.calls = list(responses), []

    def generate(self, prompt, images=None):
        """Record the real prompt/current image and return one scripted response.

        Args:
            prompt: Prompt assembled by production Reasoning.
            images: The single production observation path.
        Raises:
            Exception: The script supplies an error or receives too many calls.
        Returns:
            str: Original prediction text.
        """
        self.calls.append((prompt, images))
        response = self.responses.pop(0)
        if isinstance(response, Exception):
            raise response
        return response


class Android:
    """Record actual executor calls behind the shared Android service boundary."""

    platform, serial, w, h = "android", "seeclick-fake", 100, 200

    def __init__(self, broken=False):
        """Initialize effects and capture logs with optional execution failure.

        Args:
            broken: Fail the next physical tap.
        Returns:
            None.
        """
        self.effects, self.images, self.broken = [], [], broken

    def screenshot(self, path):
        """Write a distinct real PNG for each shared observation activation.

        Args:
            path: Runtime-owned output file.
        Returns:
            str: Current screenshot path.
        """
        Image.new("RGB", (self.w, self.h), (len(self.images), 0, 0)).save(path)
        self.images.append(str(path))
        return path

    def get_xml(self, path):
        """Reject UI-tree capture because the SeeClick graph is visual-only.

        Args:
            path: Unexpected XML destination.
        Raises:
            AssertionError: The caller unexpectedly requests XML.
        Returns:
            None.
        """
        raise AssertionError("SeeClick must not request XML")

    def tap(self, x, y):
        """Record a confirmed tap, or inject a device error.

        Args:
            x: Horizontal pixel coordinate.
            y: Vertical pixel coordinate.
        Raises:
            RuntimeError: Controlled device failure is enabled.
        Returns:
            None.
        """
        if self.broken:
            raise RuntimeError("controlled device failure")
        self.effects.append(("tap", x, y))

    def input_text(self, text):
        """Record typing without additional focus, clearing or Enter.

        Args:
            text: Exact requested text.
        Returns:
            None.
        """
        self.effects.append(("text", text))

    def shell(self, command):
        """Record the precise swipe generated by the shared executor.

        Args:
            command: A canonical input swipe command.
        Returns:
            str: Empty shell output.
        """
        assert command.startswith("input swipe ")
        self.effects.append(("swipe", command))
        return ""

    def go_back(self):
        """Record a BACK key effect.

        Returns:
            None.
        """
        self.effects.append(("back",))

    def go_home(self):
        """Record a HOME key effect.

        Returns:
            None.
        """
        self.effects.append(("home",))

    def enter(self):
        """Record an explicit Enter key effect.

        Returns:
            None.
        """
        self.effects.append(("enter",))


def reasoning_input(history=()):
    """Build an input with distracting generic prompt/plan content.

    Args:
        history: Original SeeClick action fragments.
    Returns:
        ReasoningInput: Raw screenshot input and irrelevant fields to exclude.
    """
    return ReasoningInput(TaskInput("Open settings"), PlanResult("DO NOT INJECT PLAN"),
        PerceptionResult("screenshot", "current.png", metadata=SIZE,
                         visual_representations=["marked.png"], prompt_representation="DO NOT INJECT NOTES"),
        memory_context=tuple(history), available_apps="DO NOT INJECT APPS")


def run_graph(tmp_path, responses, *, max_steps=20, max_decisions=30, device=None, yaml=False):
    """Execute production components and shared services with bounded fake I/O.

    Args:
        tmp_path: Isolated artifact directory.
        responses: External model response script.
        max_steps: Physical interaction limit.
        max_decisions: Independent decision iteration limit.
        device: Optional failure-injecting fake Android.
        yaml: Use the public YAML entry rather than the SDK factory.
    Returns:
        tuple: Production run result, model log and device effect log.
    """
    source = load_graph_yaml(ROOT / "examples/graphs/seeclick_online.yaml") if yaml else build_seeclick_graph(
        max_steps=max_steps, max_decisions=max_decisions)
    model, android = Model(responses), device or Android()
    result = compile_agent(source, dependencies={"llm": model}).run("Open settings",
        AgentRunConfig(artifact_root=tmp_path, max_steps=max_steps), device=android)
    return result, model, android


