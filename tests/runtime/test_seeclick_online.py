@pytest.mark.fake_device_integration
@pytest.mark.parametrize("yaml", [False, True])
def test_graph_executes_all_mobile_effects_and_four_step_history(tmp_path, yaml):
    """Run actual SDK/YAML components and executor across more than four rounds.

    Args:
        tmp_path: Isolated trajectory destination.
        yaml: Public authoring entry to exercise.
    Raises:
        AssertionError: The source or execution contract is violated.
    Returns:
        None.
    """
    responses = ['{"action_type":4,"click_point":(0.25,0.75)}',
                 '{"action_type":3,"typed_text":"Ab C"}',
                 *[str({"action_type":i}) for i in (0,1,8,9,5,6,7,10)]]
    result, model, device = run_graph(tmp_path, responses, yaml=yaml)
    assert result.status is RunStatus.SUCCESS, result
    assert result.interaction_count == 9
    assert device.effects == [("tap",25,150), ("text","Ab C"),
        ("swipe","input swipe 50 160 50 40 400"), ("swipe","input swipe 50 40 50 160 400"),
        ("swipe","input swipe 20 100 80 100 400"), ("swipe","input swipe 80 100 20 100 400"),
        ("back",), ("home",), ("enter",)]
    assert len(model.calls) == len(device.images) == 10
    for index,(prompt,images) in enumerate(model.calls):
        history = "".join(f"Step{i}: {raw}. " for i,raw in enumerate(responses[max(0,index-4):index]))
        assert prompt == CONTRACT["prompt"].format("Open settings",history)
        assert images == [device.images[index]]
    assert (tmp_path / result.run_id / "manifest.json").is_file()
    assert result.action_results[-1].action.type is ActionType.DONE
    assert not result.action_results[-1].effect_performed


