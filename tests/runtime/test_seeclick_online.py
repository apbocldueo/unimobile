def test_memory_window_is_run_owned_bounded_and_exact():
    """Separate two contexts while keeping only four original prediction texts.

    Raises:
        AssertionError: The source or execution contract is violated.
    Returns:
        None.
    """
    memory, contexts = SeeClickMemory(), [RuntimeContext(), RuntimeContext()]
    for number in range(7):
        raw = str({"action_type": 3, "typed_text": f"value {number}"})
        action = SeeClickActionParser().parse(raw, SIZE)
        memory.invoke(MemoryInput(MemoryOperation.APPEND,
                      MemoryFragment("assistant", FragmentType.ACTION, action)), contexts[0])
        memory.invoke(MemoryInput(MemoryOperation.APPEND,
                      MemoryFragment("system", FragmentType.ERROR, "do not include")), contexts[0])
    values = memory.invoke(MemoryInput(MemoryOperation.READ), contexts[0]).fragments
    assert [item.content for item in values] == [str({"action_type":3,"typed_text":f"value {i}"}) for i in range(3,7)]
    assert memory.invoke(MemoryInput(MemoryOperation.READ), contexts[1]).fragments == ()
    memory.invoke(MemoryInput(MemoryOperation.RESET), contexts[0])
    assert memory.invoke(MemoryInput(MemoryOperation.READ), contexts[0]).fragments == ()


